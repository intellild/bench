#!/usr/bin/env node

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.dirname(fileURLToPath(import.meta.url));
const fixturesRoot = path.join(projectRoot, 'fixtures');
const moduleCount = readPositiveInteger(
  'RSPACK_LOADER_CACHE_BENCH_MODULES',
  1000,
);
const slowLoaderComplexity = readPositiveInteger(
  'RSPACK_LOADER_CACHE_BENCH_COMPLEXITY',
  200,
);
const scenarios = [
  { name: 'backend-only', complexity: 1 },
  { name: 'slow-loader', complexity: slowLoaderComplexity },
];

function readPositiveInteger(name, fallback) {
  const value = Number(process.env[name] ?? fallback);
  if (!Number.isSafeInteger(value) || value <= 0) {
    throw new Error(`${name} must be a positive integer`);
  }
  return value;
}

async function writeScenario({ name, complexity }) {
  const scenarioRoot = path.join(fixturesRoot, name);
  const srcDir = path.join(scenarioRoot, 'src');
  await fs.rm(scenarioRoot, { recursive: true, force: true });
  await fs.mkdir(srcDir, { recursive: true });

  const imports = [
    '// Generated by generate-fixtures.mjs. Do not edit by hand.',
  ];
  for (let index = 0; index < moduleCount; index++) {
    const filename = `module-${index}.js`;
    imports.push(`import value${index} from './${filename}';`);
    const statements = Array.from(
      { length: complexity },
      (_, statementIndex) =>
        `total += ({ value: total + ${statementIndex} })?.value ?? 0;`,
    );
    await fs.writeFile(
      path.join(srcDir, filename),
      [
        '// Generated by generate-fixtures.mjs. Do not edit by hand.',
        `let total = ${index};`,
        ...statements,
        'export default total;',
        '',
      ].join('\n'),
    );
  }
  imports.push(
    `globalThis.__loaderCacheBench = ${Array.from(
      { length: moduleCount },
      (_, index) => `value${index}`,
    ).join(' + ')};`,
    '',
  );
  await fs.writeFile(path.join(srcDir, 'index.js'), imports.join('\n'));

  const loaderSetup =
    name === 'slow-loader'
      ? String.raw`
const babelLoader = process.env.RSPACK_LOADER_CACHE_BENCH_BABEL_LOADER;
if (!babelLoader) {
  throw new Error('RSPACK_LOADER_CACHE_BENCH_BABEL_LOADER is required');
}
`
      : '';
  const loaderRequest =
    name === 'slow-loader'
      ? 'babelLoader'
      : "path.join(__dirname, 'identity-loader.cjs')";
  const loaderOptions =
    name === 'slow-loader'
      ? String.raw`            options: {
              babelrc: false,
              configFile: false,
            },
`
      : '';

  if (name === 'backend-only') {
    await fs.writeFile(
      path.join(scenarioRoot, 'identity-loader.cjs'),
      String.raw`// Generated by generate-fixtures.mjs. Do not edit by hand.
module.exports = function identityLoader(source) {
  return source;
};
`,
    );
  }

  await fs.writeFile(
    path.join(scenarioRoot, 'rspack.config.cjs'),
    String.raw`// Generated by generate-fixtures.mjs. Do not edit by hand.
const path = require('node:path');
${loaderSetup}

module.exports = {
  context: __dirname,
  mode: 'development',
  devtool: false,
  cache: {
    type: 'persistent',
    version: 'loader-cache-bench-v1',
    buildDependencies: [],
    storage: {
      type: 'filesystem',
      directory: path.join(__dirname, '.cache'),
    },
  },
  experiments: {
    loaderCache: true,
  },
  entry: './src/index.js',
  output: {
    path: path.join(__dirname, 'dist'),
    filename: 'main.js',
  },
  optimization: {
    minimize: false,
  },
  module: {
    rules: [
      {
        test: /module-\d+\.js$/,
        type: 'javascript/auto',
        use: [
          {
            loader: ${loaderRequest},
${loaderOptions}            cache: true,
          },
        ],
      },
    ],
  },
};
`,
  );
}

await fs.rm(fixturesRoot, { recursive: true, force: true });
await fs.mkdir(fixturesRoot, { recursive: true });
for (const scenario of scenarios) {
  await writeScenario(scenario);
}
await fs.writeFile(
  path.join(fixturesRoot, 'manifest.json'),
  `${JSON.stringify({ moduleCount, scenarios }, null, 2)}\n`,
);

console.log(
  `Generated ${scenarios.length} fixtures with ${moduleCount} modules each`,
);
